  /**
   * 核心分类与收支判定函数（支持双向原子词根、正负号、免动词固有收入、极简口语单字兜底）
   * @param {string} rawSegment 原始短句（含正负号、动词、金额，如 "股票+500"、"早10"、"工资15000"）
   * @param {string} cleanNote  剥离日期和金额数字后的纯文本备注（如 "股票"、"早"、"工资"）
   * @returns {{ type: 'expense' | 'income', category: string }}
   */
  function matchCategoryAndType(rawSegment, cleanNote) {
    const text = (rawSegment || '').trim();
    const note = (cleanNote || text).trim();

    // A. 检测显式正负号（如 "股票 +500" 记收入，"股票 -300" 记支出）
    const hasPlusSign = /(?:^|[^\d])[+＋]\s*\d/.test(text);
    const hasMinusSign = /(?:^|[^\d])[-－]\s*\d/.test(text);

    // B. 检测强收支倾向特征词
    const strongIncomeRegex = /收到|收了|入账|到账|赚了|赚|盈利|止盈|落袋|分红|股息|派息|利息|退回|退款|退了|退货|退税|报销|理赔|返现|返利|卖出|卖了|出手|转卖|回血|中奖|发了|发工资|发薪|回款|尾款|兼职|外快|副业|稿费|收红包|抢红包|别人还|还我/;
    const strongExpenseRegex = /花了|买了|买|充了|交了|付了|扣了|扣费|消费|支出|亏了|亏损|割肉|止损|被套|定投|加仓|补仓|建仓|续费|订阅|随礼|发红包|给红包|包红包|送礼|请客|借给|借出|捐款|罚款|赔了/;

    const hasIncomeVerb = strongIncomeRegex.test(text);
    const hasExpenseVerb = strongExpenseRegex.test(text);

    // C. 在支出字典与收入字典中分别寻找“最长匹配关键字”
    let bestExpCat = '';
    let bestExpKw = '';
    for (const [cat, keywords] of Object.entries(expenseKeywordMap)) {
      for (const kw of keywords) {
        if (text.includes(kw) && kw.length > bestExpKw.length) {
          bestExpKw = kw;
          bestExpCat = cat;
        }
      }
    }

    let bestIncCat = '';
    let bestIncKw = '';
    for (const [cat, keywords] of Object.entries(incomeKeywordMap)) {
      for (const kw of keywords) {
        if (text.includes(kw) && kw.length > bestIncKw.length) {
          bestIncKw = kw;
          bestIncCat = cat;
        }
      }
    }

    // D. 裁决收支类型 (type) 与最终分类 (category)
    // 规则 1：显式正负号优先级最高
    if (hasPlusSign && !hasMinusSign) {
      return {
        type: 'income',
        category: bestIncCat || singleCharIncomeMap[note] || (bestExpCat === '投资理财' || bestExpCat === '数字资产' || bestExpCat === '礼金人情' ? bestExpCat : '其他收入')
      };
    }
    if (hasMinusSign && !hasPlusSign) {
      return {
        type: 'expense',
        category: bestExpCat || singleCharExpenseMap[note] || '其他支出'
      };
    }

    // 规则 2：存在明确收入动作词且无支出动作词（如 "股票赚了500"、"收到红包200"、"基金回血300"）
    if (hasIncomeVerb && !hasExpenseVerb) {
      return {
        type: 'income',
        category: bestIncCat || '其他收入'
      };
    }

    // 规则 3：存在明确支出动作词且无收入动作词（如 "买股票500"、"发红包200"）
    if (hasExpenseVerb && !hasIncomeVerb) {
      return {
        type: 'expense',
        category: bestExpCat || '其他支出'
      };
    }

    // 规则 4：无明显动词或动词冲突时，比较双向字典命中的关键字长度与固有属性
    if (bestIncKw.length > 0 || bestExpKw.length > 0) {
      // 若收入字典命中的词更长（如 "利息 50"、"股票盈利 300"、"年终奖 10000"），直接判为收入
      if (bestIncKw.length > bestExpKw.length) {
        return { type: 'income', category: bestIncCat };
      }
      // 若支出字典命中的词更长，直接判为支出
      if (bestExpKw.length > bestIncKw.length) {
        return { type: 'expense', category: bestExpCat };
      }
      // 若两边命中长度相同（如简写 "工资 10000"、"报销 200"、"股票 500"、"红包 100"）：
      // 属于工资/营业/兼职/奖金/退款这 5 大固有收入类的，免动词直接判为收入；其余中性词（如单纯写 "股票 500"、"红包 100"）默认归为支出
      if (INTRINSIC_INCOME_CATEGORIES.includes(bestIncCat)) {
        return { type: 'income', category: bestIncCat };
      }
      return { type: 'expense', category: bestExpCat };
    }

    // E. 规则 5：长字典均未命中时，若有效备注 <= 2 个字，启用极简口语单字映射兜底（如 "早10"、"药25"、"油200"）
    if (note.length > 0 && note.length <= 2) {
      for (const char of note) {
        if (hasIncomeVerb && singleCharIncomeMap[char]) {
          return { type: 'income', category: singleCharIncomeMap[char] };
        }
        if (singleCharExpenseMap[char]) {
          return { type: 'expense', category: singleCharExpenseMap[char] };
        }
        if (singleCharIncomeMap[char]) {
          return { type: 'income', category: singleCharIncomeMap[char] };
        }
      }
    }

    // F. 终极兜底
    return {
      type: hasIncomeVerb ? 'income' : 'expense',
      category: hasIncomeVerb ? '其他收入' : '其他支出'
    };
  }

